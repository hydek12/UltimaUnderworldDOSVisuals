"""Emit the Japanese Rev 1 Lanugo rendering hooks."""

from mipswords import Code

# Keep the original actor projection and hit testing. Suppress only Lanugo's mesh packets.
def suppress(origin, order_table_register="v1"):
    c=Code(origin)
    c.mem("lw","t8",0x74,"sp")
    c.address("t9",0x8002a5d8)
    c.branch("bne","t8","t9","normal")
    c.mem("lw","t8",0x158,"sp")
    c.imm("ori","t9","zero",10)
    c.mem("lbu","t8",26,"t8")
    c.nop()
    c.branch("bne","t8","t9","normal")
    c.nop()
    c.mem("sh","s3",0x18c,"sp")
    c.jump(0x8002b684)
    c.nop()
    c.label("normal")
    c.jump(0x8002b684)
    c.mem("sw","v0",0,order_table_register)
    return c.out()

def draw(origin, metadata):
    c=Code(origin)
    c.mem("lw","t0",0xe0,"sp")
    c.imm("ori","t1","zero",10)
    c.mem("lbu","t2",26,"t0")
    c.nop()
    c.branch("bne","t2","t1","finish")
    c.nop()
    c.alu("subu","t1","a3","a1")
    c.branch("blez","t1","zero","finish")
    c.nop()
    c.imm("sltiu","t2","t1",256)
    c.branch("beq","t2","zero","finish")
    c.nop()
    # Compute the viewer's octant in world coordinates. North = 0, east = 2.
    c.mem("lh","t3",0xe8,"sp")
    c.mem("lh","t4",0xf8,"sp")
    c.mem("lhu","t5",2,"t0")
    c.alu("slt","t6","zero","t3")
    c.alu("slt","t7","zero","t4")
    c.branch("bne","t6","zero","x_pos")
    c.nop()
    c.alu("subu","t3","zero","t3")
    c.label("x_pos")
    c.branch("bne","t7","zero","z_pos")
    c.nop()
    c.alu("subu","t4","zero","t4")
    c.label("z_pos")
    c.shift("srl","t5","t5",7)
    c.imm("andi","t5","t5",7)
    # Near an axis, use a cardinal view. Compare 5*min with 2*max.
    c.shift("sll","t8","t3",2)
    c.alu("addu","t8","t8","t3")
    c.shift("sll","t9","t4",1)
    c.alu("sltu","t2","t8","t9")
    c.branch("bne","t2","zero","north_south")
    c.nop()
    c.shift("sll","t8","t4",2)
    c.alu("addu","t8","t8","t4")
    c.shift("sll","t9","t3",1)
    c.alu("sltu","t2","t8","t9")
    c.branch("bne","t2","zero","east_west")
    c.nop()
    c.branch("beq","t7","zero","north_diagonal")
    c.nop()
    c.shift("sll","t2","t6",1)
    c.branch("beq","zero","zero","octant")
    c.imm("addiu","t2","t2",3)
    c.label("north_diagonal")
    c.shift("sll","t2","t6",1)
    c.alu("subu","t2","zero","t2")
    c.branch("beq","zero","zero","octant")
    c.imm("addiu","t2","t2",1)
    c.label("north_south")
    c.branch("beq","zero","zero","octant")
    c.shift("sll","t2","t7",2)
    c.label("east_west")
    c.shift("sll","t2","t6",2)
    c.imm("addiu","t2","t2",2)
    c.label("octant")
    c.alu("subu","t2","t5","t2")
    c.imm("addiu","t2","t2",4)
    c.imm("andi","t2","t2",7)
    c.shift("sll","t2","t2",3)
    c.address("t0",metadata)
    c.alu("addu","t0","t0","t2")

    # Pass the original projected foot/center through the DOS hotspot.
    c.mem("lbu","t2",2,"t0") # width
    c.mem("lbu","t3",3,"t0") # height
    c.mem("lbu","t4",4,"t0") # hotspot x
    c.mem("lbu","t5",5,"t0") # hotspot y
    c.muldiv("multu","t1","t4")
    c.nop()
    c.mflo("t4")
    c.muldiv("divu","t4","t3")
    c.alu("addu","t8","a0","a2")
    c.shift("sra","t8","t8",1)
    c.mflo("t4")
    c.alu("subu","t8","t8","t4") # left
    c.muldiv("multu","t1","t5")
    c.nop()
    c.mflo("t5")
    c.muldiv("divu","t5","t3")
    c.nop()
    c.mflo("t5")
    c.alu("subu","t9","a3","t5") # top
    c.muldiv("multu","t1","t2")
    c.nop()
    c.mflo("t2")
    c.muldiv("divu","t2","t3")
    c.mem("lhu","t4",0,"t0") # packed base uv
    c.mem("lbu","t5",2,"t0")
    c.mflo("t2")
    c.alu("addu","t2","t8","t2") # right
    c.alu("addu","t3","t9","t1") # bottom

    c.imm("lui","t6","zero",0x800d)
    c.mem("lw","t7",-0x6188,"t6") # packet alloc
    c.mem("lw","v0",-0x6168,"t6") # packet end
    c.imm("addiu","v1","t7",0x28)
    c.alu("sltu","v0","v0","v1")
    c.branch("bne","v0","zero","finish")
    c.nop()
    c.mem("sw","v1",-0x6188,"t6")
    c.mem("lw","v0",-0x6138,"t6")
    c.mem("lhu","v1",0x114,"sp")
    c.mem("lw","v0",0x70,"v0")
    c.shift("sll","v1","v1",2)
    c.imm("addiu","v0","v0",0x400)
    c.alu("addu","v0","v0","v1")
    c.mem("lw","v1",0,"v0")
    c.address("t6",0x00ffffff)
    c.alu("AND","v1","v1","t6")
    c.alu("AND","t6","t7","t6")
    c.imm("lui","t1","zero",0x0900)
    c.alu("OR","v1","v1","t1")
    c.mem("sw","v1",0,"t7")
    c.mem("sw","t6",0,"v0")
    # Opaque raw-texture quad preserves the RGB555 palette entries.
    c.imm("lui","v1","zero",0x2d00)
    c.mem("sw","v1",4,"t7")
    c.imm("andi","t8","t8",0xffff)
    c.imm("andi","t2","t2",0xffff)
    c.shift("sll","t9","t9",16)
    c.shift("sll","t3","t3",16)
    c.alu("OR","v1","t8","t9")
    c.mem("sw","v1",8,"t7")
    c.alu("OR","v1","t2","t9")
    c.mem("sw","v1",16,"t7")
    c.alu("OR","v1","t8","t3")
    c.mem("sw","v1",24,"t7")
    c.alu("OR","v1","t2","t3")
    c.mem("sw","v1",32,"t7")
    c.imm("lui","v1","zero",0x401c)
    c.alu("OR","v1","v1","t4")
    c.mem("sw","v1",12,"t7")
    c.imm("addiu","t5","t5",-1)
    c.alu("addu","t5","t4","t5")
    c.imm("lui","v1","zero",0x16)
    c.alu("OR","v1","v1","t5")
    c.mem("sw","v1",20,"t7")
    c.mem("lbu","v1",3,"t0")
    c.nop()
    c.imm("addiu","v1","v1",-1)
    c.shift("sll","v1","v1",8)
    c.alu("addu","t4","t4","v1")
    c.mem("sw","t4",28,"t7")
    c.alu("addu","t5","t5","v1")
    c.mem("sw","t5",36,"t7")
    c.label("finish")
    c.jump(0x800757c4)
    c.nop()
    return c.out()
